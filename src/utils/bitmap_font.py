def draw_char_bmp(
    pixel_buffer: bytearray,
    char: str,
    x: int,
    y: int,
    color_bgr: bytes,
    scale: int,
    width: int,
    height: int
) -> int:
    """Draws a single scaled 8x8 character into a 24-bit bottom-up BMP pixel buffer.
    
    Returns:
        Advance width in pixels.
    """
    char_upper = char.upper()
    pattern = FONT_8X8.get(char_upper, FONT_8X8.get(' ', [0]*8))
    
    # Calculate row size with padding for 24-bit BMP
    row_bytes = width * 3
    padding = (4 - (row_bytes % 4)) % 4
    stride = row_bytes + padding

    for row_idx in range(8):
        byte_val = pattern[row_idx]
        for col_idx in range(8):
            if (byte_val >> (7 - col_idx)) & 1:
                # Draw scale x scale block
                for dy in range(scale):
                    # In bottom-up BMP: screen y is inverted
                    pixel_y = y + (row_idx * scale) + dy
                    inv_y = (height - 1) - pixel_y
                    if not (0 <= inv_y < height):
                        continue

                    for dx in range(scale):
                        pixel_x = x + (col_idx * scale) + dx
                        if not (0 <= pixel_x < width):
                            continue

                        offset = (inv_y * stride) + (pixel_x * 3)
                        pixel_buffer[offset : offset + 3] = color_bgr

    return (8 + 1) * scale

def draw_text_bmp(
    pixel_buffer: bytearray,
    text: str,
    x: int,
    y: int,
    color_bgr: bytes,
    scale: int,
    width: int,
    height: int
) -> None:
    """Draws a text string onto a bottom-up BMP pixel buffer."""
    curr_x = x
    for ch in text:
        advance = draw_char_bmp(pixel_buffer, ch, curr_x, y, color_bgr, scale, width, height)
        curr_x += advance
