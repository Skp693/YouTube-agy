"""Base stage class defining the interface and contracts for pipeline stages."""

from abc import ABC, abstractmethod
import traceback
from config.logging_config import setup_logger
from src.models import ProjectState
from src.utils.file_manager import FileManager

class BaseStage(ABC):
    """Abstract base class for all pipeline stages."""

    stage_number: int
    stage_name: str

    def __init__(self) -> None:
        self.logger = setup_logger(f"stage_{self.stage_number}_{self.stage_name}")

    def run(self, state: ProjectState) -> ProjectState:
        """Standard wrapper that executes validation, processing, and error handling.
        
        Args:
            state: Current pipeline ProjectState.
            
        Returns:
            Updated ProjectState after stage completion.
        """
        self.logger.info(f"=== Starting Stage {self.stage_number}: {self.stage_name} ===")
        state.current_stage = self.stage_number
        state.status = "in_progress"

        try:
            # Pre-execution validation
            self.validate_prerequisites(state)
            
            # Stage implementation logic
            state = self.execute(state)
            
            # Post-execution validation
            self.validate_output(state)
            
            # Checkpoint save
            FileManager.save_state(state)
            self.logger.info(f"=== Completed Stage {self.stage_number}: {self.stage_name} ===")
            return state

        except Exception as exc:
            state.status = "failed"
            state.error_message = f"Error in Stage {self.stage_number} ({self.stage_name}): {str(exc)}"
            self.logger.error(state.error_message)
            self.logger.debug(traceback.format_exc())
            FileManager.save_state(state)
            raise

    @abstractmethod
    def validate_prerequisites(self, state: ProjectState) -> None:
        """Validate required state inputs before executing the stage."""
        pass

    @abstractmethod
    def execute(self, state: ProjectState) -> ProjectState:
        """Core logic for this stage."""
        pass

    @abstractmethod
    def validate_output(self, state: ProjectState) -> None:
        """Validate output generated by this stage before advancing."""
        pass
